#!/usr/bin/env bash
# Writes kn_bench.cr: crystal-metric's Fasta and Knuckeotide classes verbatim
# from bench/crystal_metric/metric.cr, behind a minimal Benchmark base.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
metric="$here/../../../crystal_metric/metric.cr"
start=$(grep -n '^class Fasta < Benchmark' "$metric" | cut -d: -f1)
stop=$(grep -n '^class Mandelbrot < Benchmark' "$metric" | cut -d: -f1)
{
  echo "# Generated by extract.sh from bench/crystal_metric/metric.cr lines $start-$((stop - 1))."
  echo "abstract class Benchmark"
  echo "  def ok?"
  echo "    result == expected"
  echo "  end"
  echo "end"
  echo
  sed -n "${start},$((stop - 1))p" "$metric"
} >"$here/kn_bench.cr"
